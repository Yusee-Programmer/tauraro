#!/usr/bin/env python3
"""Generate std/sys/tz_table.tr: the embedded IANA-name -> POSIX TZ rule table
used by std.sys.tz when no zoneinfo directory exists (Windows, minimal images).

Every zone Python's zoneinfo lists (zoneinfo.available_timezones()) is read
from the system tzdata, and the POSIX TZ footer of its TZif file (RFC 8536
section 3.3, the rule in force after the last listed transition) becomes its
entry. Zones sharing a rule are grouped to keep the table small.

    python3 scripts/gen_tz_table.py [ZONEINFO_DIR] > std/sys/tz_table.tr

Re-run after a tzdata release changes current rules. The output records the
tzdata version it was generated from.
"""
import os, sys, zoneinfo

def footer(path):
    data = open(path, "rb").read()
    if data[:4] != b"TZif" or data[4] < 0x32:
        return None
    end = data.rstrip(b"\n").rfind(b"\n")
    return data[end + 1:].rstrip(b"\n").decode("ascii")

def main():
    zdir = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    version = "unknown"
    try:
        with open(os.path.join(zdir, "tzdata.zi")) as f:
            first = f.readline().strip()
            if first.startswith("# version "):
                version = first[len("# version "):]
    except OSError:
        pass
    groups = {}
    for name in sorted(zoneinfo.available_timezones()):
        rule = footer(os.path.join(zdir, name))
        if not rule or " " in rule or ";" in rule or '"' in rule or "\\" in rule:
            continue
        groups.setdefault(rule, []).append(name)
    entries = [rule + " " + " ".join(names) + " ;" for rule, names in sorted(groups.items())]
    chunks, cur = [], ""
    for e in entries:
        if cur and len(cur) + len(e) > 2000:
            chunks.append(cur)
            cur = ""
        cur += e
    if cur:
        chunks.append(cur)
    out = sys.stdout
    out.write("# std.sys.tz_table -- GENERATED by scripts/gen_tz_table.py; do not edit.\n")
    out.write(f"# tzdata {version}: {sum(len(v) for v in groups.values())} zones, {len(groups)} distinct rules.\n")
    out.write("#\n# Each group is \"POSIX-RULE name name ... ;\". Only the CURRENT rule of each\n")
    out.write("# zone is kept: std.sys.tz uses this when no TZif file is available, so\n")
    out.write("# historical offsets (before the zone's present rule) are not reproduced.\n\n")
    out.write(f"pub const TZ_TABLE_VERSION = \"{version}\"\n\n")
    for i, c in enumerate(chunks):
        out.write(f"const _TZT_{i} = \"{c}\"\n")
    out.write(f"\n# Number of chunks (see tz_table_chunk).\npub def tz_table_chunks() -> int: return {len(chunks)}\n\n")
    out.write("pub def tz_table_chunk(i: int) -> str:\n")
    for i in range(len(chunks)):
        out.write(f"    if i == {i}: return _TZT_{i}\n")
    out.write("    return \"\"\n")

main()
